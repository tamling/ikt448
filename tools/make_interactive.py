def slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def main() -> None:
    for no, exercises in EX.items():
        nn = f"{no:02d}"
        out = [f"<!-- Interactive exercises for chapter {no}; generated by tools/make_interactive.py, included from chapters/{nn}-{SLUGS[no]}.qmd -->", ""]
        for ex in exercises:
            eid = f"exr-{nn}-{slug(ex['title'])}-interactive"
            out.append(f"::: {{#{eid}}}")
            out.append(f"## {ex['title']}, interactive")
            out.append("")
            out.append(ex["intro"] + " Then press **Check**.")
            out.append("")
            out.append("```{=html}")
            out.append(f'<div class="grc-ex" data-type="{ex["type"]}">')
            out.append('<script type="application/json">')
            out.append(json.dumps(ex["cfg"], ensure_ascii=False, indent=1))
            out.append("</script>")
            out.append("</div>")
            out.append("```")
            out.append(":::")
            out.append("")
        (ROOT / "chapters" / f"_{nn}-interactive.qmd").write_text("\n".join(out))
        print(f"chapters/_{nn}-interactive.qmd: {len(exercises)} exercises")


if __name__ == "__main__":
    main()
