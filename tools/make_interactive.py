def sort(title, intro, buckets, chips, explain, ref, reflabel):
    return dict(type="sort", title=title, intro=intro,
                cfg=dict(buckets=[dict(id=b[0], label=b[1], **({"desc": b[2]} if len(b) > 2 else {})) for b in buckets],
                         chips=[dict(t=t, b=b) for t, b in chips],
                         explain=explain, ref=ref, reflabel=reflabel))


def order(title, intro, steps, explain, ref, reflabel, hint=None):
    cfg = dict(steps=steps, explain=explain, ref=ref, reflabel=reflabel)
    if hint:
        cfg["hint"] = hint
    return dict(type="order", title=title, intro=intro, cfg=cfg)


def pick(title, intro, options, explain, ref, reflabel, prompt=None):
    cfg = dict(options=[dict(t=t, ok=ok) for t, ok in options], explain=explain, ref=ref, reflabel=reflabel)
    if prompt:
        cfg["prompt"] = prompt
    return dict(type="pick", title=title, intro=intro, cfg=cfg)


